/** Generate declared build-source identity; explanations and this manifest are intentionally excluded. */
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {VERSION,MODEL_VERSION,DATA_VERSION} from '../src/version.js';

export const ENGINE_MODULE_PATHS=Object.freeze([
  'src/data.js','src/evidence.generated.js','src/frozen-run.js','src/model.js',
  'src/optimizer.worker.js','src/release-state.js','src/spatial-inputs.js','src/version.js'
]);
function canonical(value){
  if(Array.isArray(value))return `[${value.map(canonical).join(',')}]`;
  if(value&&typeof value==='object')return `{${Object.keys(value).sort().map(k=>`${JSON.stringify(k)}:${canonical(value[k])}`).join(',')}}`;
  return JSON.stringify(value);
}
const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
export async function buildEngineIdentity(root=new URL('../',import.meta.url)){
  const modules=[];
  for(const path of ENGINE_MODULE_PATHS){const bytes=await fs.readFile(new URL(path,root));modules.push({path,bytes:bytes.length,sha256:sha256(bytes)});}
  const payload={format:'FarmSystemDesign.EngineSource.v1',algorithm:'SHA-256',applicationVersion:VERSION,
    modelVersion:MODEL_VERSION,dataVersion:DATA_VERSION,modules};
  return {...payload,digest:sha256(`FarmSystemDesign/engine-source/v1\n${canonical(payload)}`)};
}
export async function generateEngineIdentity(){
  const identity=await buildEngineIdentity();
  await fs.writeFile(new URL('../src/engine-identity.generated.js',import.meta.url),
    `/** Generated by tools/generate-engine-identity.mjs. Declared source identity, not runtime attestation. */\nexport const ENGINE_IDENTITY = ${JSON.stringify(identity,null,2)};\n`);
  const metadataURL=new URL('../version.json',import.meta.url),metadata=JSON.parse(await fs.readFile(metadataURL,'utf8'));
  metadata.engineDigest=identity.digest;await fs.writeFile(metadataURL,`${JSON.stringify(metadata,null,2)}\n`);
  return identity;
}
if(process.argv[1]===fileURLToPath(import.meta.url))console.log(`Engine source SHA-256: ${(await generateEngineIdentity()).digest}`);
